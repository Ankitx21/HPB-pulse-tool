/* One-page ASSURE scorecard. Artwork comes from the supplied report template. */
(function () {
  const GOOD = '#6ba438', BAD = '#ff542e', WARN = '#f6b500', INK = '#111111';

  async function buildBuildingReport(inputs, results, date = new Date()) {
    await document.fonts.ready;
    const image = new Image();
    await new Promise((resolve, reject) => {
      image.onload = resolve;
      image.onerror = () => reject(new Error('Report artwork could not be loaded.'));
      image.src = new URL('buildinge_health_tool_asset/report-background.jpg', document.baseURI).href;
    });
    const canvas = document.createElement('canvas');
    canvas.width = 1785;
    canvas.height = 2526;
    const ctx = canvas.getContext('2d');
    ctx.drawImage(image, 0, 0, canvas.width, canvas.height);
    ctx.scale(3, 3);
    const family = 'Poppins, Arial, sans-serif';
    function text(value, x, y, width, size = 17, color = INK) {
      value = String(value);
      ctx.fillStyle = color;
      ctx.textBaseline = 'alphabetic';
      ctx.font = `500 ${size}px ${family}`;
      while (ctx.measureText(value).width > width && size > 8) {
        size -= 0.25;
        ctx.font = `500 ${size}px ${family}`;
      }
      ctx.fillText(value, x, y, width);
    }
    function note(value, x, y, width) {
      ctx.fillStyle = INK;
      ctx.font = `400 9px ${family}`;
      const words = value.split(/\s+/);
      let line = '';
      for (const word of words) {
        const next = line ? line + ' ' + word : word;
        if (line && ctx.measureText(next).width > width) {
          ctx.fillText(line, x, y); y += 11; line = word;
        } else line = next;
      }
      if (line) ctx.fillText(line, x, y);
    }
    const number = (v, digits = 1) => Number.isFinite(v)
      ? v.toLocaleString('en-IN', { maximumFractionDigits: digits }) : 'Not available';
    const finite = Number.isFinite;
    const parts = new Intl.DateTimeFormat('en-GB', {
      day: '2-digit', month: '2-digit', year: 'numeric', timeZone: 'Asia/Kolkata'
    }).format(date).replaceAll('/', '-');
    text(`Generated by HPB Pulse on ${parts}`, 34, 157, 527, 16);
    text((inputs.projectName || '').trim(), 45, 224, 155);
    text(inputs.city || '', 220, 224, 158);
    text(finite(inputs.areaSqm) ? `${number(inputs.areaSqm)} m²` : 'Not available', 395, 224, 164);

    const starText = results.starRating?.text || '';
    const match = starText.match(/\((\d) Star\)/);
    const starCount = match ? Number(match[1]) : 0;
    const notApplicable = /not defined/.test(starText);
    const starMissing = !match && starText !== 'No Star';
    text(notApplicable ? 'Not applicable' : starMissing ? 'Not available' : `${starCount} Star`, 44, 439, 158, 18,
      notApplicable || starMissing ? WARN : starCount >= 4 ? GOOD : starCount === 3 ? WARN : BAD);
    note(notApplicable ? 'BEE ratings are not defined for cold climate zones.' : starMissing ? 'Result not available due to missing input(s).' : starCount ? `${starCount}-Star energy performance` : 'Zero-star energy performance', 44, 457, 158);

    const epi = results.epi;
    text(finite(epi) ? `${number(epi)} kWh/m²/year` : 'Not available', 218, 439, 160, 18, finite(epi) && epi <= 75 ? GOOD : WARN);
    note(!finite(epi) ? 'Result not available due to missing input(s).' : epi <= 75 ? 'Within ASSURE KPI ≤75 kWh/m²/year' : 'Above ASSURE KPI of 75 kWh/m²/year', 218, 457, 160);

    const demand = results.annualEnergyDemand, gen = results.renewableGenKWh;
    const validNet = finite(demand) && demand > 0 && finite(gen);
    const offset = validNet ? gen / demand * 100 : NaN;
    const tolerance = Math.max(1, .005 * demand);
    const netZero = validNet && gen > 0 && Math.abs(results.netEnergy) <= tolerance;
    const netPositive = validNet && results.netEnergy > tolerance;
    text(!validNet ? 'Not available' : netZero ? 'Net Zero' : netPositive ? 'Net Positive' : 'Net Negative', 396, 439, 164, 18, netZero || netPositive ? GOOD : WARN);
    note(validNet ? `Renewables offset ${number(offset, 0)}% of consumption` : 'Result not available due to missing input(s).', 396, 457, 164);

    const hvac = results.hvacSizing?.sfPerTR;
    const cd = results.demandSizing?.cdWsf;
    const dg = results.demandSizing?.dgWsf;
    const water = results.lpcd;
    const missing = 'Result not available due to missing input(s).';
    const bottom = [
      [44, 116, hvac, 'sqft/TR', finite(hvac) && hvac >= 700 && hvac <= 800, results.hvacSizing?.status],
      [175, 117, cd, 'W/sqft', finite(cd) && cd <= 5, finite(cd) && cd <= 5 ? 'Right-sized power capacity' : 'More power capacity than needed'],
      [308, 117, dg, 'W/sqft', finite(dg) && dg <= 5, finite(dg) && dg <= 5 ? 'Right amount of power back-up' : 'More backup power than needed'],
      [441, 117, water, 'lpcd', finite(water) && water <= 45, finite(water) && water <= 45 ? 'Usage within recommended limit' : 'Usage above recommended limit']
    ];
    for (const [x, width, value, unit, good, message] of bottom) {
      text(finite(value) ? `${number(value, unit === 'sqft/TR' ? 0 : unit === 'W/sqft' ? 2 : 1)} ${unit}` : 'Not available', x, 538, width, 17, good ? GOOD : unit === 'lpcd' ? WARN : BAD);
      note(finite(value) ? message : missing, x, 555, width);
    }
    return imagePdf(canvas.toDataURL('image/jpeg', .97).split(',')[1], canvas.width, canvas.height);
  }

  // Minimal PDF writer for a single high-resolution scorecard, without a CDN dependency.
  function imagePdf(base64, width, height) {
    const jpeg = Uint8Array.from(atob(base64), c => c.charCodeAt(0));
    const encoder = new TextEncoder();
    const chunks = [], offsets = [0];
    let length = 0;
    const add = data => { const bytes = typeof data === 'string' ? encoder.encode(data) : data; chunks.push(bytes); length += bytes.length; };
    const object = (id, content) => { offsets[id] = length; add(`${id} 0 obj\n${content}\nendobj\n`); };
    add('%PDF-1.4\n');
    object(1, '<< /Type /Catalog /Pages 2 0 R >>');
    object(2, '<< /Type /Pages /Kids [3 0 R] /Count 1 >>');
    object(3, '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /XObject << /Artwork 4 0 R >> >> /Contents 5 0 R >>');
    offsets[4] = length;
    add(`4 0 obj\n<< /Type /XObject /Subtype /Image /Width ${width} /Height ${height} /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length ${jpeg.length} >>\nstream\n`);
    add(jpeg); add('\nendstream\nendobj\n');
    const stream = 'q 595 0 0 842 0 0 cm /Artwork Do Q\n';
    object(5, `<< /Length ${encoder.encode(stream).length} >>\nstream\n${stream}endstream`);
    const xref = length;
    add('xref\n0 6\n0000000000 65535 f \n');
    for (let i = 1; i <= 5; i++) add(`${String(offsets[i]).padStart(10, '0')} 00000 n \n`);
    add(`trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`);
    return new Blob(chunks, { type: 'application/pdf' });
  }
  window.buildBuildingReport = buildBuildingReport;
})();
